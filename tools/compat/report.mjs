/* Turns the matrix JSON into docs/compatibility.md.
   Usage: node tools/compat/report.mjs [matrix.json] [output.md] */

import { readFileSync, writeFileSync } from 'node:fs'

const input = process.argv[2] ?? 'output/compatibility.json'
const output = process.argv[3] ?? 'docs/compatibility.md'
const rows = JSON.parse(readFileSync(input, 'utf8'))

const TIERS = [
  ['static', 'Static', 'Renders on the server; binds no events.'],
  ['server-interactive', 'Server-rendered, interactive', 'Renders on the server; its events become Messages on the server.'],
  ['server-submodel', 'Server-side Submodel', 'A stateful component running on the server (Model, update, view); every interaction is a round trip.'],
  ['degraded', 'Degraded', 'Works on the server, but a browser-only part is missing: an `OnMount` hook is dropped or a browser-only Command is skipped (focus, scrolling, positioning, dialogs). Fine where that part does not matter; otherwise use an island.'],
  ['island', 'Island required', 'Uses an event the server cannot bind (file uploads). Run it as a Foldkit island.'],
  ['error', 'Error', 'Does not render.'],
]

const count = tier => rows.filter(row => row.tier === tier).length
const list = values => (values.length === 0 ? '' : values.map(value => `\`${value}\``).join(', '))

const notes = row =>
  [
    row.dropped.length > 0 ? `drops ${list(row.dropped)}` : '',
    row.browserCommands.length > 0 ? `skips ${list(row.browserCommands)}` : '',
    row.forwardedCommands.length > 0 ? `forwards ${list(row.forwardedCommands)}` : '',
    row.unsupported.length > 0 ? `needs ${list(row.unsupported)}` : '',
    row.errors.length > 0 ? row.errors.join('; ').replace(/\|/g, '\\|').slice(0, 160) : '',
  ]
    .filter(note => note !== '')
    .join('; ')

const summary = results => {
  const failed = (results ?? []).filter(result => result !== 'ok' && result !== 'none')
  if (failed.length > 0) return `fails (${failed.length})`
  return (results ?? []).some(result => result === 'ok') ? 'ok' : 'n/a'
}
const interaction = row => summary(row.interactions)
const keyboard = row => summary(row.keyboard)

const lines = [
  '# crease/ui on hyper-effect: compatibility matrix',
  '',
  `Generated by \`npm run check:compat\` from crease/ui's own component demos (${rows.length} components, every example). Each example is rendered through hyper-effect's server builder with Foldkit's markup validation on. Interactive examples also get one smoke interaction: the first clickable Message (or a typed value) is decoded, run through \`update\`, its Commands are tried, and the result is rendered again. Examples with keyboard handlers also get a keyboard pass: ArrowDown, ArrowDown, Enter and Escape, each on the first key handler that takes it, with \`update\` and the Commands run after every press (a Command that needs a browser on that path is listed under *skips*).`,
  '',
  '| Tier | Components | Meaning |',
  '|---|---|---|',
  ...TIERS.map(([tier, title, meaning]) => `| ${title} | ${count(tier)} | ${meaning} |`),
  '',
  'Column notes: *drops* lists browser-only hooks removed on the server, *skips* lists browser-only Commands that fail on the server, and *forwards* lists Commands sent to the browser instead (client command forwarding).',
  '',
]

for (const [tier, title] of TIERS) {
  const group = rows.filter(row => row.tier === tier).sort((a, b) => a.slug.localeCompare(b.slug))
  if (group.length === 0) continue
  lines.push(`## ${title} (${group.length})`, '', '| Component | Kind | Examples | Bound events | Interaction | Keys | Notes |', '|---|---|---|---|---|---|---|')
  for (const row of group) {
    const events = [
      row.messages > 0 ? `${row.messages} Message` : '',
      row.handlers.length > 0 ? list(row.handlers) : '',
      row.inputs > 0 ? `${row.inputs} input` : '',
    ]
      .filter(part => part !== '')
      .join(', ')
    lines.push(`| ${row.title} | ${row.kind} | ${row.examples} | ${events || '—'} | ${interaction(row)} | ${keyboard(row)} | ${notes(row) || '—'} |`)
  }
  lines.push('')
}

writeFileSync(output, `${lines.join('\n')}\n`)
console.log(`wrote ${output}`)
